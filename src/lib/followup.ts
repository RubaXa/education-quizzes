export type FollowUpSource = {
  title: string
  subject: string
  slug: string
  token: string
}

export function buildFollowUpPrompt(item: FollowUpSource, site = 'https://rubaxa.github.io/education-quizzes/'): string {
  const resultUrl = `${site}#/t/${item.slug}~${item.token}`
  return `Создай для ученик связанный онлайн-тест после работы «${item.title}» (${item.subject}).

Результат: ${resultUrl}
В проекте PETR используй skills/online-quiz/SKILL.md. Получи сохранённую попытку и ключ через Firebase API или командой из education-quizzes: npm run quiz -- export ${item.token} .local/follow-up-source.json. Не проси ученика переписывать ответы.

Сначала отдели подтверждённые ошибки от верных ответов, пропусков и вопросов с ручной проверкой. Выдели правила и точные источники, на которые опирался разбор. Уровень самостоятельности считай неизвестным, если он не зафиксирован.

Составь новый тест, связанный с исходным testId: несколько адресных заданий по ошибкам, задания по текущему материалу и перенос в новые ситуации. Не повторяй дословно старые вопросы и не заполняй весь тест одной ошибкой. Если проблема повторяется или уже исправлялась после подсказки, добавь различающий вопрос чуть сложнее. Сохрани сильные стороны: не заставляй многократно доказывать уже верное. Для математики выбор варианта не считай доказательством самостоятельных письменных вычислений.

Для каждого вопроса подготовь правильный ответ, правило, объяснение ошибки, точное место в материале и следующий шаг. Проверь ключ, выполни preflight и quiz validate, создай назначение в Firebase, проверь публичную страницу и дай мне ученическую ссылку и предпросмотр.`
}
