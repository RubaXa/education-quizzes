// @vitest-environment jsdom
/** @see ../../docs/modules/families/browser-access-trace.md */
import { beforeEach, expect, it, vi } from 'vitest'
import { createAccessTrace, formatAccessLog, inspectAccessTrace } from './browserAccessTrace'

beforeEach(() => sessionStorage.clear())
it('prints the function, state transition and decision details without draft scope APIs', () => {
  const journal = createAccessTrace({ now: () => 1000, runId: 'run' })
  journal.record('access.resolved', { atFunction: 'configureRoleDiagnostics', previousState: 'checking', state: 'resolved', role: 'student', previousRole: 'student', source: 'member-server', fromCache: false })
  const row = journal.snapshot().events[0]
  expect(formatAccessLog(row)).toBe('[configureRoleDiagnostics] [checking → resolved] Use role from membership document')
  expect(row.detail).toMatchObject({ role: 'student', previousRole: 'student', fromCache: false })
})
it('rejects arbitrary function names and state strings before logging', () => {
  const journal = createAccessTrace({ now: () => 1000, runId: 'run' })
  journal.record('access.failed', { atFunction: 'SECRET_LINK', previousState: 'private-token', state: 'student-work-text', code: 'permission-denied' })
  expect(JSON.stringify(journal.snapshot())).not.toMatch(/SECRET_LINK|private-token|student-work-text/)
})
it('marks a truncated local journal incomplete and preserves its dropped count on reload', () => {
  const journal = createAccessTrace({ storage: sessionStorage, now: () => 1000, runId: 'run' })
  for (let index = 0; index < 215; index++) journal.record('view.rendered', { role: 'student' })
  expect(journal.coverage()).toEqual({ complete: false, droppedRecords: 15 })
  expect(createAccessTrace({ storage: sessionStorage, now: () => 1001, runId: 'next' }).coverage()).toEqual({ complete: false, droppedRecords: 15 })
})
it('does not claim complete coverage for a legacy journal without a truncation counter', () => {
  sessionStorage.setItem('education-access-trace-v1', JSON.stringify({ schemaVersion: 1, events: [{ runId: 'old', sequence: 1, at: 999, event: 'app.loaded', detail: {} }] }))
  expect(createAccessTrace({ storage: sessionStorage, now: () => 1000, runId: 'new' }).coverage()).toMatchObject({ complete: false, coverageUnknown: true })
})
it('records ordered decisions, persists across reload and exports no arbitrary payload or credentials', () => {
  const journal = createAccessTrace({ storage: sessionStorage, now: () => 1000, runId: 'run-one' })
  journal.record('identity.resolved', { role: 'parent', source: 'local', reason: 'cache-hit', linkToken: 'SECRET', personId: 'PERSON' } as any)
  journal.record('view.rendered', { role: 'student', source: 'card', hasGuide: false })
  expect(journal.snapshot().events.map((event) => event.sequence)).toEqual([1, 2])
  expect(JSON.stringify(journal.snapshot())).not.toMatch(/SECRET|PERSON|linkToken|personId/)
  const reloaded = createAccessTrace({ storage: sessionStorage, now: () => 1001, runId: 'run-two' })
  expect(reloaded.snapshot().events).toHaveLength(2)
  expect(inspectAccessTrace(reloaded.snapshot()).findings).toContain('parent-context-student-view')
})
it('rejects poisoned stored data and values, keeps only a bounded journal and survives denied storage', () => {
  sessionStorage.setItem('education-access-trace-v1', JSON.stringify({ events: [{ event: 'view.rendered', detail: { role: 'SECRET' } }] }))
  const journal = createAccessTrace({ storage: sessionStorage, now: () => 1000, runId: 'run' })
  journal.record('view.rendered', { role: 'SECRET', source: 'https://secret', reason: 'TOKEN' } as any)
  expect(JSON.stringify(journal.snapshot())).not.toMatch(/SECRET|https|TOKEN/)
  for (let index = 0; index < 250; index++) journal.record('view.rendered', { role: 'parent' })
  expect(journal.snapshot().events.length).toBe(200)
  const denied = createAccessTrace({ storage: { getItem: () => { throw Error() }, setItem: () => { throw Error() } }, now: () => 1000, runId: 'run' })
  expect(() => denied.record('access.resolved', { role: 'parent' })).not.toThrow()
})
it('distinguishes local student identity from a proven parent projection failure and separate runs', () => {
  const journal = createAccessTrace({ now: () => 1000, runId: 'run' })
  journal.record('identity.resolved', { role: 'student', source: 'local' })
  journal.record('access.resolved', { role: 'student', source: 'member-server' })
  journal.record('view.rendered', { role: 'student', source: 'card' })
  expect(inspectAccessTrace(journal.snapshot()).findings).toContain('student-membership-student-view')
  expect(inspectAccessTrace(journal.snapshot()).findings).not.toContain('parent-context-student-view')
  expect(inspectAccessTrace({ schemaVersion: 1, events: [] }).status).toBe('insufficient-evidence')
  const next = createAccessTrace({ storage: sessionStorage, now: () => 1001, runId: 'next' })
  next.record('view.rendered', { role: 'student' })
  expect(inspectAccessTrace(next.snapshot()).findings).not.toContain('parent-context-student-view')
})
it('does not let a later local cache hit erase authoritative membership evidence', () => {
  const journal = createAccessTrace({ now: () => 1000, runId: 'run' })
  journal.record('access.resolved', { role: 'student', source: 'member-server', fromCache: false })
  journal.record('identity.resolved', { role: 'student', source: 'local' })
  journal.record('view.rendered', { role: 'student', source: 'card' })
  expect(inspectAccessTrace(journal.snapshot()).findings).toContain('student-membership-student-view')
})
it('keeps photo storage diagnostics private and outside access-role inference', () => {
  const journal = createAccessTrace({ now: () => 1000, runId: 'run' })
  journal.record('access.resolved', { role: 'parent', scope: 'a'.repeat(24), source: 'member-server' })
  journal.record('view.rendered', { role: 'student', scope: 'a'.repeat(24), source: 'card' })
  journal.record('photo.storage', { atFunction: 'savePhotoForTransfer', state: 'retrying', code: 'indexeddb-connection-lost', count: 2, durationMs: 16,
    role: 'parent', source: 'member-server', person: 'b'.repeat(24), scope: 'c'.repeat(24), title: 'PRIVATE_NAME', message: 'PRIVATE_ERROR', url: 'PRIVATE_URL', blob: 'PRIVATE_BLOB' } as any)
  const trace = journal.snapshot()
  expect(trace.events[2].detail).toEqual({ atFunction: 'savePhotoForTransfer', state: 'retrying', code: 'indexeddb-connection-lost', count: 2, durationMs: 16 })
  expect(JSON.stringify(trace)).not.toMatch(/PRIVATE_NAME|PRIVATE_ERROR|PRIVATE_URL|PRIVATE_BLOB/)
  expect(inspectAccessTrace(trace).findings).toContain('parent-context-student-view')
  expect(inspectAccessTrace({ schemaVersion: 1, events: [{ runId: 'run', sequence: 1, at: 1000, event: 'photo.storage', detail: { role: 'parent', source: 'member-server', state: 'failed' } }] }).findings).toEqual([])
})
it('keeps photo-help events in the same bounded trace with a narrow private-safe schema', () => {
  const journal = createAccessTrace({ storage: sessionStorage, now: () => 1000, runId: 'run' })
  journal.record('help.interaction', { action: 'submitted', context: 'demo', role: 'student', count: 2, hasNote: true,
    note: 'PRIVATE_TEXT', fileName: 'PRIVATE_FILE', url: 'PRIVATE_URL', scope: 'a'.repeat(24), code: 'PRIVATE_ERROR' } as any)
  journal.record('help.interaction', { action: 'PRIVATE_ACTION', context: 'PRIVATE_CONTEXT', role: 'PRIVATE_ROLE', count: -1, hasNote: 'PRIVATE_NOTE' } as any)
  const trace = journal.snapshot()
  expect(trace.events[0].detail).toEqual({ action: 'submitted', context: 'demo', role: 'student', count: 2, hasNote: true })
  expect(trace.events[1].detail).toEqual({})
  expect(JSON.stringify(trace)).not.toMatch(/PRIVATE_|aaaaaaaa/)
  expect(formatAccessLog(trace.events[0])).toBe('[tracePhotoHelp] [unknown → submitted] Observe photo help interaction: submitted')
  expect(createAccessTrace({ storage: sessionStorage, now: () => 1001, runId: 'next' }).snapshot().events[0].detail).toEqual(trace.events[0].detail)
  expect(inspectAccessTrace(trace).findings).toEqual([])
  journal.record('help.interaction', { action: 'failed', context: 'product', role: 'student', code: 'sync-failed' })
  journal.record('help.interaction', { action: 'submitted', context: 'product', role: 'student', code: 'sync-failed' })
  expect(journal.snapshot().events[2].detail.code).toBe('sync-failed')
  expect(journal.snapshot().events[3].detail.code).toBeUndefined()
})
it('limits lesson interaction diagnostics to fixed actions and never retains answers or identifiers', () => {
  const journal = createAccessTrace({ storage: sessionStorage, now: () => 1000, runId: 'run' })
  journal.record('lesson.interaction', { action: 'choice-selected', context: 'demo', role: 'student', count: 2,
    answer: 'PRIVATE_ANSWER', question: 'PRIVATE_QUESTION', lessonId: 'PRIVATE_ID', photo: 'PRIVATE_PHOTO', hasNote: true, code: 'sync-failed' } as any)
  journal.record('lesson.interaction', { action: 'failed', context: 'product', role: 'parent', code: 'sync-failed' })
  journal.record('lesson.interaction', { action: 'PRIVATE_ACTION', context: 'PRIVATE_CONTEXT', role: 'PRIVATE_ROLE', count: -3, code: 'PRIVATE_ERROR' } as any)
  const trace = journal.snapshot()
  expect(trace.events[0].detail).toEqual({ action: 'choice-selected', context: 'demo', role: 'student', count: 2 })
  expect(trace.events[1].detail).toEqual({ action: 'failed', context: 'product', role: 'parent', code: 'sync-failed' })
  expect(trace.events[2].detail).toEqual({})
  expect(JSON.stringify(trace)).not.toContain('PRIVATE_')
  expect(formatAccessLog(trace.events[0])).toBe('[traceLesson] [unknown → choice-selected] Observe lesson interaction: choice-selected')
  expect(createAccessTrace({ storage: sessionStorage, now: () => 1001, runId: 'next' }).snapshot().events).toEqual(trace.events)
  expect(inspectAccessTrace(trace).findings).toEqual([])
})
it('applies the existing 200 event cap to photo storage diagnostics', () => {
  const journal = createAccessTrace({ now: () => 1000, runId: 'run' })
  for (let attempt = 1; attempt <= 205; attempt++) journal.record('photo.storage', { atFunction: 'localPhotoForTransfer', state: 'checking', count: attempt })
  expect(journal.snapshot().events).toHaveLength(200)
  expect(journal.coverage()).toEqual({ complete: false, droppedRecords: 5 })
})
it('does not claim a role contradiction for different children or overwrite one card with another', () => {
  const journal = createAccessTrace({ now: () => 1000, runId: 'run' })
  journal.record('access.resolved', { role: 'parent', scope: 'a'.repeat(24), source: 'member-server' })
  journal.record('view.rendered', { role: 'student', scope: 'b'.repeat(24), source: 'card' })
  expect(inspectAccessTrace(journal.snapshot()).findings).not.toContain('parent-context-student-view')
  expect(vi.isMockFunction(journal.record)).toBe(false)
})
it('retains decision order when hashes arrive later and compares a mounted view with later membership', () => {
  const journal = createAccessTrace({ now: () => 1000, runId: 'run' })
  const first = journal.record('view.rendered', { role: 'student', source: 'card' })
  journal.record('access.resolved', { role: 'parent', scope: 'a'.repeat(24), source: 'member-server' })
  journal.enrich(first, { scope: 'a'.repeat(24) })
  expect(journal.snapshot().events.map(event => event.event)).toEqual(['view.rendered', 'access.resolved'])
  expect(inspectAccessTrace(journal.snapshot()).findings).toContain('parent-context-student-view')
})
it('sanitizes the local logger sink too and ignores sink failure and expired history', () => {
  const emit = vi.fn()
  const journal = createAccessTrace({ storage: sessionStorage, now: () => 1000, runId: 'run', emit })
  journal.record('identity.resolved', { role: 'parent', linkToken: 'SECRET' } as any)
  expect(JSON.stringify(emit.mock.calls)).not.toContain('SECRET')
  expect(createAccessTrace({ storage: sessionStorage, now: () => 25 * 60 * 60_000, runId: 'next' }).snapshot().events).toHaveLength(0)
  const broken = createAccessTrace({ emit: () => { throw Error() } })
  expect(() => broken.record('app.loaded', {})).not.toThrow()
})
