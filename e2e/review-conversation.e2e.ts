/** @see ../docs/shared/design/student-review-step.md */
import {test,expect} from '@playwright/test'
for(const width of[320,390,540])test(`reply feedback and next step ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900});await page.goto('#/ui-kit')
 await page.getByRole('navigation').getByRole('button',{name:'Компактный разбор',exact:true}).click()
 const demo=page.getByRole('region',{name:'Ответ и следующий шаг',exact:true}),review=demo.locator('.edu-review-brief')
 await review.getByRole('button',{name:'Сторона C',exact:true}).focus();await page.keyboard.press('Space')
 await expect(review.getByRole('button',{name:'Отправить ответ',exact:true})).toBeEnabled()
 await review.getByRole('button',{name:'Отправить ответ',exact:true}).click()
 await expect(review).toContainText('Ответ отправлен');await expect(review.locator('.edu-step-tokens')).toHaveCount(0)
 await demo.getByRole('button',{name:'Показать проверенный отклик',exact:true}).click()
 await expect(review.locator('.edu-step-feedback')).toContainText('Ты нашёл сторону')
 await expect(review.locator('.edu-review-question')).toHaveText('Сколько раз общая сторона входила в сумму периметров до соединения?')
 await expect(review.getByRole('textbox')).toHaveValue('')
 await review.getByRole('button',{name:'Непонятно',exact:true}).click()
 await expect(review).toContainText('Вопрос отправлен')
 await review.getByText('Дополнить вопрос',{exact:true}).click()
 await review.getByRole('textbox',{name:'Что именно непонятно?',exact:true}).fill('Не понимаю, как считать сторону до склейки')
 await review.getByRole('button',{name:'Отправить пояснение',exact:true}).click()
 await review.getByText('Что отправлено',{exact:true}).click()
 await expect(review).toContainText('Не понимаю, как считать сторону до склейки')
 await demo.getByRole('combobox',{name:'Результат проверки примера',exact:true}).selectOption('stuck')
 await demo.getByRole('button',{name:'Показать проверенный отклик',exact:true}).click()
 await expect(review.locator('.edu-step-feedback')).toContainText('Пойдём от одной фигуры')
 expect(await review.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 for(const c of await review.locator('button,input,textarea,summary').all())if(await c.isVisible())expect(await c.evaluate(el=>el.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
 await demo.getByRole('button',{name:'Родитель смотрит',exact:true}).click()
 await expect(review.getByRole('button',{name:'Непонятно',exact:true})).toHaveCount(0)
 await expect(review.getByRole('button',{name:'Отправить ответ',exact:true})).toHaveCount(0)
})
