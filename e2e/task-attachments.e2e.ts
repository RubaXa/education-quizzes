/** @see ../docs/shared/design/ui-kit.md#вложения-в-карточке-задания */
import { expect, test } from '@playwright/test'
const controlStyle = (node: HTMLElement) => {
  const s=getComputedStyle(node)
  return Object.fromEntries(['display','height','fontSize','fontWeight','lineHeight','paddingTop','paddingRight','paddingBottom','paddingLeft','borderRadius','backgroundColor','color'].map(key=>[key,s[key as keyof CSSStyleDeclaration]]))
}
for (const width of [320,390,540]) test(`canonical attachment controls retain the actual day/weekend variants at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:1000})
  await page.goto('#/ui-kit')
  // Characterize the already-shipped control before opening the new composition.
  await page.getByRole('button',{name:'Письменная задача',exact:true}).click()
  await page.getByText('№ 1. Письменная задача · пример',{exact:true}).click()
  const referenceUpload=await page.locator('#demo-written .problem-card-actions .problem-card-upload').evaluate(controlStyle)
  await page.locator('#demo-written .day-upload-chip').first().click()
  const referenceClose=await page.locator('#demo-written .day-upload-close').evaluate(controlStyle)
  await page.getByRole('button',{name:'Файлы и превью',exact:true}).click()
  const example=page.getByRole('region',{name:'Вложения в карточке задания',exact:true})
  async function openTask(){const card=example.locator('.problem-card');if(!await card.evaluate(node=>(node as HTMLDetailsElement).open))await card.locator(':scope>summary').click()}
  await openTask()
  expect(await example.locator('.problem-card-actions .problem-card-upload').evaluate(controlStyle)).toEqual(referenceUpload)
  await expect(example.locator('.day-upload-head')).toContainText('Файлы работы')
  await expect(example.locator('.day-upload-chip')).toHaveCount(3)
  await expect(example.locator('.weekend-math-photo-delete')).toHaveCount(0)
  const chipBounds=await example.locator('.day-upload-chip').first().boundingBox()
  expect(chipBounds!.width).toBe(38);expect(chipBounds!.height).toBe(38)
  await example.locator('.day-upload-chip').first().click()
  const image=example.locator('.day-upload-expanded img');await expect(image).toBeVisible()
  await expect.poll(()=>image.evaluate(node=>(node as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  expect(await example.locator('.day-upload-close').evaluate(controlStyle)).toEqual(referenceClose)
  await example.locator('.day-upload-chip').nth(1).click()
  await expect(example.locator('.day-upload-expanded strong')).toHaveText('Решение.pdf')
  await expect(example.locator('.day-upload-expanded img')).toHaveCount(0)
  expect(await example.evaluate(node=>node.scrollWidth>node.clientWidth+1)).toBe(false)
  await example.getByRole('button',{name:'Выходной лист',exact:true}).click();await openTask()
  await expect(example.locator('.day-upload-head')).toHaveCount(0)
  await expect(example.locator('.weekend-math-photo-delete')).toHaveCount(3)
  await example.getByRole('button',{name:'Родитель',exact:true}).click()
  await expect(example.locator('input[type=file]')).toHaveCount(0)
  await expect(example.locator('.weekend-math-photo-delete')).toHaveCount(0)
  await example.getByRole('button',{name:'Ученик',exact:true}).click()
  await example.getByRole('button',{name:'Ошибка файла',exact:true}).click()
  await example.locator('.day-upload-chip').nth(1).click()
  await expect(example.locator('.day-upload-expanded')).toContainText('Условная ошибка передачи файла')
  await example.locator('.weekend-math-photo-delete').nth(1).click()
  await expect(example.locator('.day-upload-chip')).toHaveCount(2)
  await example.getByRole('button',{name:'Получено',exact:true}).click()
  await example.getByRole('button',{name:'Карточка дня',exact:true}).click();await openTask()
  await example.locator('.day-upload-chip').first().click()
  await example.locator('.day-subject').screenshot({path:`.local/canonical-task-attachments-${width}.png`})
})
