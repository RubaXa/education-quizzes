/** @see ../docs/shared/design/student-review-step.md */
import{test,expect}from'@playwright/test'
for(const width of[320,390,540])for(const parent of[false,true])test(`current learner step ${width}px parent=${parent}`,async({page})=>{
 await page.setViewportSize({width,height:900});await page.goto('#/ui-kit')
 await page.getByRole('navigation').getByRole('button',{name:'Компактный разбор',exact:true}).click()
 const catalogue=page.getByRole('region',{name:'Компактный разбор',exact:true})
 if(parent)await catalogue.getByRole('button',{name:'Родитель',exact:true}).click()
 const review=catalogue.locator('.day-review-stack').first()
 await review.getByRole('button',{name:'5',exact:true}).click();await review.getByRole('button',{name:'3',exact:true}).click()
 await expect(review.locator('output')).toHaveText(/5\s*\+\s*3/)
 await expect(review.locator('output')).not.toContainText('8')
 await expect(review.locator('math')).toBeVisible()
 await catalogue.getByRole('button',{name:'Геометрия',exact:true}).click()
 await review.getByRole('button',{name:'Сторона C',exact:true}).focus();await page.keyboard.press('Space')
 await expect(review.getByRole('button',{name:'Сторона C',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(review.locator('.edu-step-diagram .is-selected')).toHaveCount(1)
 await catalogue.getByRole('button',{name:'Своя запись',exact:true}).click()
 await review.getByRole('textbox',{name:'Твоё слово',exact:true}).fill('большой')
 await expect(review.locator('output')).toHaveText('большой дом')
 await catalogue.getByRole('button',{name:'Группировка',exact:true}).click()
 await review.getByRole('combobox',{name:'Куда поместить: Автор торопился.',exact:true}).selectOption('guess')
 await expect(review.getByRole('status')).toContainText('ПредположениеАвтор торопился.')
 await catalogue.getByRole('button',{name:'Зачтено',exact:true}).click()
 await expect(review.locator('.edu-step')).toHaveCount(0);await expect(review.locator('.edu-review-question')).toHaveCount(0)
 await catalogue.getByRole('button',{name:'Есть правка',exact:true}).click()
 for(const c of await review.locator('.edu-step button,.edu-step input,.edu-step select').all())expect(await c.evaluate(el=>el.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
 expect(await review.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 if(!parent)await expect(catalogue.getByText('Полный путь: метод и случаи',{exact:true})).toHaveCount(0)
})
